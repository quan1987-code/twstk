def concept_map():
    """回傳 {sid: [概念, ...]}，一檔可有多個概念（依 CONCEPTS 定義順序）。"""
    out = {}
    for concept, sids in CONCEPTS.items():
        for sid in sids:
            if len(sid) == 4 and sid.isdigit() and not sid.startswith("00"):
                lst = out.setdefault(sid, [])
                if concept not in lst:
                    lst.append(concept)
    return out


